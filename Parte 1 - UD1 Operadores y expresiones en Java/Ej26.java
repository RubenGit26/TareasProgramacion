public class Ej26 {
    public static void main(String[] args) {
        int saldo = 100;

        System.out.println("Saldo principal: " + saldo);

        saldo += 50;
        System.out.println("Saldo tras sumarle 50€: " + saldo + "€");
    
        saldo -= 20;
        System.out.println("Saldo tras restarle 20€: " + saldo + "€");
    
        saldo *= 2;
        System.out.println("Saldo tras duplicar el saldo actual: " + saldo + "€");

        saldo /= 4;
        System.out.println("Saldo tras dividirlo entre 4: " + saldo + "€");

        System.out.println("Saldo restante: " + saldo + "€");
    
    
    
    
    }
}
