/*
 * En este programa calcularemos el area de un circulo.
 * Este declarará e inicializará el radio del circulo. Este tipo entero
 * Declararemos e inicializaremos el area del circulo, tipo double. PI * r²
 */
public class Ej19 {
    public static void main(String[] args) {
        int radio = 5;//Declaramos la variable radio y la inicializamos en 5
        double area = 3.1416 * radio * radio;//Declaramos la variable area y la inicializamos (Pi * r² (3.1416 * radio * radio (3.1416 * 5 * 5)))
        System.out.println(area);//Esta mostrará la variable area, es decir, el resultado de 3.1416 * 5 * 5
    }
}
